namespace XE_Local_AI_Engine.Client.Services.Benchmarks.PythonTests;

using System.Reflection;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using XE_Local_AI_Engine.Client.Services.Compute;

/// <summary>
///     Composes the two Python programs a <c>pythonTests</c> criterion runs, and reads the verdict back out of what the
///     sandbox printed.
///     <para>
///         The <b>parent</b> is trusted: it holds the nonce and the operator's test code, runs those tests itself
///         against a proxy, and prints one nonce-marked verdict line. The <b>child</b> is untrusted: it executes the
///         model's candidate code and answers JSON <c>call</c>/<c>eval</c> requests. They are two processes inside the
///         same per-invocation bwrap jail, and the process that computes the verdict never executes the graded code.
///     </para>
///     <para>
///         <b>Everything variable is base64.</b> The candidate, the operator's tests and the config cross into Python
///         as base64 constants, so no byte of untrusted (or merely awkward) text ever participates in a Python parse:
///         a candidate containing <c>"""</c>, a trailing backslash or a NUL cannot escape its literal, because the
///         base64 alphabet cannot close a string. The candidate is decoded only inside the untrusted child.
///     </para>
/// </summary>
internal static class BenchmarkPythonTestsHarness
{
    /// <summary>The verdict line's prefix, before the nonce. Public so tests can assert on the wire form.</summary>
    public const string MarkerPrefix = "<<<XE-PYTEST:";

    /// <summary>The longest <c>testCode</c> a policy may carry, enforced at activation so an operator learns early.</summary>
    public const int TestCodeMaxChars = 4000;

    /// <summary>The default per-call read deadline in the parent, clamped to <c>ComputeOptions.TimeoutSeconds</c>.</summary>
    public const int DefaultTimeoutSeconds = 30;

    private const string ParentResourceSuffix = "PythonTests.xe-pythontests-parent.py";
    private const string ChildResourceSuffix = "PythonTests.xe-pythontests-child.py";

    private const string NoncePlaceholder = "__XE_NONCE__";
    private const string ChildPlaceholder = "__XE_CHILD_B64__";
    private const string CandidatePlaceholder = "__XE_CANDIDATE_B64__";
    private const string TestsPlaceholder = "__XE_TESTS_B64__";
    private const string ConfigPlaceholder = "__XE_CONFIG_B64__";

    private static readonly JsonSerializerOptions VerdictOptions = new(JsonSerializerDefaults.Web);

    /// <summary>The child program's fixed part, minus the one <c>_CANDIDATE_B64</c> line the parent prepends.</summary>
    private static readonly string ChildTemplate = Minify(ReadResource(ChildResourceSuffix));

    private static readonly string ParentTemplate = Minify(ReadResource(ParentResourceSuffix));

    private static readonly string ChildTemplateBase64 =
        Convert.ToBase64String(Encoding.UTF8.GetBytes(ChildTemplate));

    /// <summary>
    ///     The composed parent for one criterion, or the reason it could not be composed. A refusal here is about the
    ///     ANSWER (it carried more code than the harness can hand to the sandbox), which is a real fact about the
    ///     candidate — not about the sandbox, which is what <see cref="ComputeRefusalCodes" /> covers.
    /// </summary>
    internal sealed record Composition(string? Program, string Nonce, string? Refusal);

    /// <summary>
    ///     The child program exactly as the parent assembles it. Exposed so a test can assert on the generated bytes
    ///     that the child holds neither the nonce nor the operator's tests — the cheapest guard against the
    ///     "just interpolate it, it's simpler" tidy-up that reintroduces the defeat this design exists to close.
    /// </summary>
    public static string ComposeChildProgram(string candidateSource)
    {
        ArgumentNullException.ThrowIfNull(candidateSource);
        return "_CANDIDATE_B64 = \"" + Convert.ToBase64String(Encoding.UTF8.GetBytes(candidateSource)) + "\"\n" + ChildTemplate;
    }

    public static Composition Compose(string candidateSource, string testCode, IReadOnlyList<string> exports, int callTimeoutSeconds)
    {
        ArgumentNullException.ThrowIfNull(candidateSource);
        ArgumentNullException.ThrowIfNull(testCode);
        ArgumentNullException.ThrowIfNull(exports);

        // Upper-case hex, because the analyzer is right that lower-casing is the culture-sensitive direction and the
        // nonce is compared byte-for-byte against what the harness prints, never parsed or displayed.
        var nonce = Convert.ToHexString(RandomNumberGenerator.GetBytes(16));
        var configBase64 = Convert.ToBase64String(JsonSerializer.SerializeToUtf8Bytes(new HarnessConfig(callTimeoutSeconds, exports), VerdictOptions));
        var testsBase64 = Convert.ToBase64String(Encoding.UTF8.GetBytes(testCode));
        var candidateBase64 = Convert.ToBase64String(Encoding.UTF8.GetBytes(candidateSource));

        var program = ParentTemplate.Replace(NoncePlaceholder, nonce, StringComparison.Ordinal)
                                    .Replace(ChildPlaceholder, ChildTemplateBase64, StringComparison.Ordinal)
                                    .Replace(CandidatePlaceholder, candidateBase64, StringComparison.Ordinal)
                                    .Replace(TestsPlaceholder, testsBase64, StringComparison.Ordinal)
                                    .Replace(ConfigPlaceholder, configBase64, StringComparison.Ordinal);
        if (program.Length > ComputeToolDefinition.CodeMaxLength)
        {
            // The composed PARENT is what the gateway receives on stdin, so it is what the ceiling applies to. Naming
            // both numbers is the point: an operator reading this can tell a runaway answer from a harness that grew.
            var overhead = program.Length - candidateBase64.Length;
            return new Composition(Program: null,
                nonce,
                $"The extracted solution is {candidateSource.Length} characters, more than the "
                + $"{Math.Max(0, (ComputeToolDefinition.CodeMaxLength - overhead) * 3 / 4)} the execution harness can carry alongside this criterion's test code.");
        }

        return new Composition(program, nonce, Refusal: null);
    }

    /// <summary>
    ///     Reads the sandbox's stdout for this invocation's marker. The table is deliberately total and has no
    ///     fail-open direction: no marker means the parent never reached its final line (the child killed it and tore
    ///     down the PID namespace, the gateway timed out, the jail was OOM-killed) and a denial of the verdict is a
    ///     failure; two or more means something forged one, which is essentially unreachable now that the only process
    ///     holding the nonce never runs the graded code, and is kept because a rule is cheaper than an argument.
    /// </summary>
    public static BenchmarkPythonTestsVerdict ReadVerdict(string standardOutput, string nonce)
    {
        ArgumentNullException.ThrowIfNull(standardOutput);
        ArgumentNullException.ThrowIfNull(nonce);

        var marker = MarkerPrefix + nonce + ">>>";
        var payloads = standardOutput.Split('\n')
                                     .Where(line => line.StartsWith(marker, StringComparison.Ordinal))
                                     .Select(line => line[marker.Length..].Trim())
                                     .ToArray();
        var foreignMarkers = standardOutput.Split('\n')
                                           .Count(line => line.StartsWith(MarkerPrefix, StringComparison.Ordinal))
                             - payloads.Length;
        if (payloads.Length == 0)
        {
            return BenchmarkPythonTestsVerdict.NoVerdict(foreignMarkers);
        }

        if (payloads.Length > 1)
        {
            return BenchmarkPythonTestsVerdict.Forged(payloads.Length, foreignMarkers);
        }

        HarnessVerdict? parsed;
        try
        {
            parsed = JsonSerializer.Deserialize<HarnessVerdict>(payloads[0], VerdictOptions);
        }
        catch (JsonException)
        {
            parsed = null;
        }

        if (parsed is null)
        {
            return BenchmarkPythonTestsVerdict.NoVerdict(foreignMarkers);
        }

        return string.Equals(parsed.Status, "unavailable", StringComparison.Ordinal)
            ? BenchmarkPythonTestsVerdict.Unavailable(parsed.Reason ?? "unknown")
            : new BenchmarkPythonTestsVerdict(Scored: parsed.Failed == 0 && parsed.Collected > 0,
                IsUnavailable: false,
                UnavailableReason: null,
                parsed.Collected,
                parsed.Passed,
                parsed.Failed,
                parsed.Phase,
                parsed.Error,
                MarkerCount: 1,
                foreignMarkers);
    }

    private static string ReadResource(string suffix)
    {
        var assembly = Assembly.GetExecutingAssembly();
        var name = assembly.GetManifestResourceNames().FirstOrDefault(candidate => candidate.EndsWith(suffix, StringComparison.Ordinal))
                   ?? throw new InvalidOperationException($"The embedded pythonTests harness resource '{suffix}' is missing from this build.");
        using var stream = assembly.GetManifestResourceStream(name)
                           ?? throw new InvalidOperationException($"The embedded pythonTests harness resource '{name}' could not be opened.");
        using var reader = new StreamReader(stream, Encoding.UTF8);
        return reader.ReadToEnd().ReplaceLineEndings("\n");
    }

    /// <summary>
    ///     Drops blank lines and whole-line comments. The templates carry a lot of prose — deliberately, because they
    ///     are the reviewed statement of a security boundary — and the composed parent has to fit inside
    ///     <see cref="ComputeToolDefinition.CodeMaxLength" /> alongside the candidate and the operator's tests.
    ///     <para>
    ///         Sound only because neither template contains a MULTI-LINE string literal, where a dropped blank line
    ///         would change a value rather than only the layout. <c>HarnessTemplatesCarryNoMultiLineStringLiteral</c>
    ///         pins that precondition, and every harness test runs the minified output rather than the source.
    ///     </para>
    /// </summary>
    private static string Minify(string template)
    {
        var kept = template.Split('\n')
                           .Where(static line => line.Trim().Length > 0 && !line.TrimStart().StartsWith('#'));
        return string.Join('\n', kept) + "\n";
    }

    private sealed record HarnessConfig(
        [property: JsonPropertyName("callTimeoutSeconds")]
        int CallTimeoutSeconds,
        [property: JsonPropertyName("exports")]
        IReadOnlyList<string> Exports);

    private sealed record HarnessVerdict(string? Status, string? Reason, int Collected, int Passed, int Failed, string? Phase, string? Error);
}

/// <summary>
///     What the harness reported. <see cref="IsUnavailable" /> is the SANDBOX saying it could not be trusted (a failed
///     <c>PR_SET_DUMPABLE</c> is the only case the parent itself raises) and must fail the judging rather than score 0;
///     everything else is a statement about the candidate, and 0 is a score an answer can genuinely earn.
/// </summary>
internal sealed record BenchmarkPythonTestsVerdict(
    bool Scored,
    bool IsUnavailable,
    string? UnavailableReason,
    int Collected,
    int PassedCount,
    int Failed,
    string? Phase,
    string? Error,
    int MarkerCount,
    int ForeignMarkerCount)
{
    public static BenchmarkPythonTestsVerdict NoVerdict(int foreignMarkers) =>
        new(Scored: false, IsUnavailable: false, UnavailableReason: null, Collected: 0, PassedCount: 0, Failed: 0,
            Phase: null, Error: null, MarkerCount: 0, foreignMarkers);

    public static BenchmarkPythonTestsVerdict Forged(int markerCount, int foreignMarkers) =>
        new(Scored: false, IsUnavailable: false, UnavailableReason: null, Collected: 0, PassedCount: 0, Failed: 0,
            Phase: null, Error: null, markerCount, foreignMarkers);

    public static BenchmarkPythonTestsVerdict Unavailable(string reason) =>
        new(Scored: false, IsUnavailable: true, reason, Collected: 0, PassedCount: 0, Failed: 0,
            Phase: null, Error: null, MarkerCount: 1, ForeignMarkerCount: 0);
}
