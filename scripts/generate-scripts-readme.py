#!/usr/bin/env python3
"""Regenerate scripts/README.md, the one-line index of every top-level script and subfolder under scripts/.

A script's line is the first sentence of its header's first paragraph: the comment block after the shebang
(shellcheck directives skipped) for a shell script, the docstring (else that comment block) for a Python script,
with a leading "<name> — " dropped. A subfolder's line is the first prose line of its README.md, else the list of
its files.
Idempotent: a second run writes the same bytes. `scripts/docs-inventory-check.py` (check `scripts-readme`) fails
when a top-level script has no row or a row names no script; re-run this after adding, removing or renaming one.

Exit codes: 0 written, 1 a top-level script has no header line to index.
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

SCRIPTS_DIR = Path(__file__).resolve().parent
README = SCRIPTS_DIR / "README.md"
SCRIPT_SUFFIXES = (".sh", ".py")
FOLDER_FILES_SHOWN = 6

PREAMBLE = """# scripts/

One line per top-level script and subfolder, taken from each script's header comment. Generated by
`scripts/generate-scripts-readme.py`; do not edit by hand. Each script's header documents its flags and exit codes.
Stopping a dev host safely: [README-dev-stop.md](README-dev-stop.md).
"""


def strip_name(line: str, name: str) -> str:
    for separator in (" — ", " - "):
        if line.startswith(name + separator):
            return line[len(name) + len(separator) :].strip()
    return line


def first_sentence(paragraph: list[str]) -> str:
    text = " ".join(paragraph)
    end = text.find(". ")
    return text[: end + 1] if end >= 0 else text


def comment_paragraph(lines: list[str]) -> list[str]:
    paragraph: list[str] = []
    for line in lines:
        stripped = line.strip()
        if stripped.startswith(("#!", "# shellcheck")):
            continue
        text = stripped.lstrip("#").strip() if stripped.startswith("#") else None
        if text:
            paragraph.append(text)
        elif paragraph or text is None and stripped:
            break
    return paragraph


def header_line(path: Path) -> str:
    """The first sentence of the header's first paragraph, without a leading "<name> — "."""
    text = path.read_text(encoding="utf-8")
    paragraph: list[str] = []
    if path.suffix == ".py":
        docstring = ast.get_docstring(ast.parse(text)) or ""
        paragraph = [line.strip() for line in docstring.strip().split("\n\n")[0].splitlines() if line.strip()]
    if not paragraph:
        paragraph = comment_paragraph(text.splitlines())
    return strip_name(first_sentence(paragraph), path.name)


def folder_line(folder: Path) -> str:
    readme = folder / "README.md"
    if readme.is_file():
        for line in readme.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.startswith("#"):
                return line.strip()
    names = sorted(
        entry.name + ("/" if entry.is_dir() else "")
        for entry in folder.iterdir()
        if not entry.name.startswith((".", "__"))
    )
    shown = ", ".join(f"`{name}`" for name in names[:FOLDER_FILES_SHOWN])
    # No count: it would go stale whenever a file is added, and the inventory check reads only the script rows.
    more = " and more" if len(names) > FOLDER_FILES_SHOWN else ""
    return f"Holds {shown}{more}."


def top_level_scripts(scripts_dir: Path) -> list[Path]:
    return sorted(path for path in scripts_dir.iterdir() if path.is_file() and path.suffix in SCRIPT_SUFFIXES)


def subfolders(scripts_dir: Path) -> list[Path]:
    return sorted(path for path in scripts_dir.iterdir() if path.is_dir() and not path.name.startswith((".", "__")))


def render(scripts_dir: Path) -> tuple[str, list[str]]:
    rows: list[str] = []
    headerless: list[str] = []
    for path in top_level_scripts(scripts_dir):
        line = header_line(path)
        if not line:
            headerless.append(path.name)
        rows.append(f"- [`{path.name}`]({path.name}) — {line}")
    folders = [f"- [`{path.name}/`]({path.name}/) — {folder_line(path)}" for path in subfolders(scripts_dir)]
    text = PREAMBLE + "\n## Scripts\n\n" + "\n".join(rows) + "\n\n## Subfolders\n\n" + "\n".join(folders) + "\n"
    return text, headerless


def main() -> int:
    text, headerless = render(SCRIPTS_DIR)
    if headerless:
        print(f"generate-scripts-readme: no header line in {', '.join(headerless)}", file=sys.stderr)
        return 1
    README.write_text(text, encoding="utf-8")
    print(f"generate-scripts-readme: wrote {README.relative_to(SCRIPTS_DIR.parent).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
